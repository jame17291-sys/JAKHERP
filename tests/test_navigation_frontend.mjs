/** Shared native-menu projection: no synthetic permissions or business actions. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
const source = fs.readFileSync(new URL('../addons/jakh_core/static/src/navigation.js', import.meta.url), 'utf8');
const { getModuleEntries, getFirstActionMenu, hasUniqueBranchAction } = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
const leaf = (id, actionID) => ({ id, actionID, childrenTree: [] });
const dashboard = leaf(2, 604);
const finance = leaf(3, 900);
const quality = leaf(5, 800);
const documents = leaf(6, 801);
const assurance = { id: 4, childrenTree: [quality, documents] };
const shell = { id: 1, xmlid: 'jakh_core.menu_construction', childrenTree: [dashboard, finance, assurance] };
const extra = leaf(7, 1000);
const menus = new Map([shell, dashboard, finance, assurance, quality, documents, extra].map((menu) => [menu.id, menu]));
let roots = [shell, extra];
const service = { getApps: () => roots, getMenuAsTree: (id) => menus.get(id) };
assert.deepEqual(getModuleEntries(service).map(({ id }) => id), [2, 3, 4, 7]);
assert.equal(getFirstActionMenu(assurance), quality);
assert.equal(getFirstActionMenu({ childrenTree: [{ childrenTree: [documents] }] }), documents);
assert.equal(getFirstActionMenu({ childrenTree: [] }), null);
assert.equal(getFirstActionMenu(extra), extra);
assert.equal(getModuleEntries(service)[2], assurance, 'Original native objects/actions are preserved');
roots = [shell, shell];
assert.deepEqual(getModuleEntries(service).map(({ id }) => id), [2, 3, 4]);
shell.childrenTree = [dashboard, assurance]; // Native service removed finance for this user.
assert.deepEqual(getModuleEntries(service).map(({ id }) => id), [2, 4]);
roots = [];
assert.deepEqual(getModuleEntries(service), []);

const savedDashboards = { id: 8, actionID: 42, name: 'Saved Dashboards', childrenTree: [leaf(9, 42)] };
assert.equal(hasUniqueBranchAction(savedDashboards), false, 'Do not add Open Saved Dashboards beside Dashboards');
assert.equal(hasUniqueBranchAction({ ...savedDashboards, actionID: '42' }), false, 'Native string and numeric IDs match');
assert.equal(hasUniqueBranchAction({ ...savedDashboards, childrenTree: [{ childrenTree: [leaf(10, 42)] }] }), false, 'Nested duplicates are reachable without an extra parent shortcut');
assert.equal(hasUniqueBranchAction({ ...savedDashboards, name: 'لوحات المعلومات المحفوظة' }), false, 'Independent of displayed language');
assert.equal(hasUniqueBranchAction({ ...savedDashboards, childrenTree: [leaf(11, 43)] }), true, 'Keep different actions even if they target the same model');
assert.equal(hasUniqueBranchAction({ ...savedDashboards, childrenTree: [{ ...leaf(11, 43), name: 'Saved Dashboards', actionPath: 'dashboards' }], actionPath: 'dashboards' }), true, 'Do not merge by name or path');
assert.equal(hasUniqueBranchAction({ ...savedDashboards, actionID: false }), false, 'Groups with no action have no shortcut');
assert.equal(hasUniqueBranchAction(leaf(12, 42)), false, 'Leaves use their regular link');
assert.equal(hasUniqueBranchAction({ id: 13 }), false, 'Empty menus have no shortcut');
const restricted = { ...savedDashboards, childrenTree: [leaf(14, 99)] };
assert.equal(hasUniqueBranchAction(restricted), true, 'Retain parent action when the matching child is permission-filtered out');
const originalTree = JSON.stringify(savedDashboards);
hasUniqueBranchAction(savedDashboards);
assert.equal(JSON.stringify(savedDashboards), originalTree, 'Native tree/actions remain unchanged');
const nested = { id: 15, actionID: 42, childrenTree: [savedDashboards] };
assert.equal(hasUniqueBranchAction(nested), false, 'Repeated actions through multiple branch levels still leave the leaf');
const uniqueNested = { id: 16, actionID: 50, childrenTree: [savedDashboards] };
assert.equal(hasUniqueBranchAction(uniqueNested), true, 'Unrelated parent action remains reachable');
const calendarSettings = { id: 17, actionID: 180, childrenTree: [leaf(18, 181)] };
assert.equal(hasUniqueBranchAction(calendarSettings, [leaf(19, 180), calendarSettings]), false, 'Calendar leaf replaces duplicate Open Configuration shortcut');
assert.equal(hasUniqueBranchAction(calendarSettings, [calendarSettings]), true, 'An inaccessible sibling must not suppress the only remaining action');
const otherBranch = { id: 20, actionID: 180, childrenTree: [leaf(21, 182)] };
assert.equal(hasUniqueBranchAction(calendarSettings, [calendarSettings, otherBranch]), true, 'Two non-leaf shortcuts cannot mutually suppress each other');
assert.equal(hasUniqueBranchAction(otherBranch, [calendarSettings, otherBranch]), true, 'Every unique branch remains reachable without a corresponding leaf');
const sidebarTemplate = fs.readFileSync(new URL('../addons/jakh_branding/static/src/sidebar.xml', import.meta.url), 'utf8');
assert.match(sidebarTemplate, /<li t-if="this\.hasUniqueBranchAction\(menu\)"/, 'Recursive sidebar template uses the duplicate guard');
console.log('Unified module navigation: 27 assertions passed.');
